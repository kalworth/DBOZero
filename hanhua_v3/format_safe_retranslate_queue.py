def protect_tokens(text: str) -> tuple[str, list[str]]:
    tokens: list[str] = []

    def repl(match: re.Match[str]) -> str:
        tokens.append(match.group(0))
        return f"{{{{{len(tokens) - 1}}}}}"

    return STRUCTURE_RE.sub(repl, text), tokens


def restore_tokens(text: str, tokens: list[str]) -> str:
    for index, token in enumerate(tokens):
        text = text.replace(f"{{{{{index}}}}}", token)
    return text


def translate_visible_segment(segment: str) -> str:
    if not segment or not segment.strip():
        return segment
    prefix = segment[: len(segment) - len(segment.lstrip())]
    suffix = segment[len(segment.rstrip()) :]
    core = segment.strip()
    raw_core = expand_contractions(core)
    if raw_core in SEGMENT_EXACT:
        return f"{prefix}{SEGMENT_EXACT[raw_core]}{suffix}"
    if raw_core in EXACT_MAP:
        return f"{prefix}{EXACT_MAP[raw_core]}{suffix}"
    printf_tokens: list[str] = []

    def protect_printf(match: re.Match[str]) -> str:
        printf_tokens.append(match.group(0))
        return f"@@P{len(printf_tokens) - 1}@@"

    core = PRINTF_RE.sub(protect_printf, core)
    core = expand_contractions(core)
    if core in SEGMENT_EXACT:
        return f"{prefix}{restore_printf(SEGMENT_EXACT[core], printf_tokens)}{suffix}"
    if core in EXACT_MAP:
        return f"{prefix}{restore_printf(EXACT_MAP[core], printf_tokens)}{suffix}"
    core = normalize_punctuation(core)
    core = expand_contractions(core)
    core = replace_possessives(core)
    for source, target in sorted(PHRASE_MAP.items(), key=lambda item: len(item[0]), reverse=True):
        if not source:
            continue
        core = re.sub(rf"(?<![A-Za-z0-9]){re.escape(source)}(?![A-Za-z0-9])", target, core, flags=re.IGNORECASE)
    core = re.sub(r"\b(\d+)(st|nd|rd|th)\b", r"第\1", core, flags=re.IGNORECASE)
    core = re.sub(r"\b([A-Za-z][A-Za-z']*)\b", replace_word, core)
    core = cleanup(core)
    core = restore_printf(core, printf_tokens)
    return f"{prefix}{core}{suffix}"


def restore_printf(text: str, tokens: list[str]) -> str:
    for index, token in enumerate(tokens):
        text = text.replace(f"@@P{index}@@", token)
    return text


def replace_possessives(text: str) -> str:
    def repl(match: re.Match[str]) -> str:
        owner = translate_word(match.group(1))
        return f"{owner}的"

    return re.sub(r"\b([A-Za-z][A-Za-z]*)'s\b", repl, text)


