def replace_word(match: re.Match[str]) -> str:
    return translate_word(match.group(1))


def translate_word(word: str) -> str:
    if re.fullmatch(r"P\d+", word):
        return word
    if word in KEEP_WORDS or re.fullmatch(r"RO\d+|[A-Z]{1,3}\d*", word):
        return word
    for key in (word, word.lower(), word.title(), word.upper()):
        value = WORD_MAP.get(key)
        if value is not None:
            return value
    if word[:1].isupper():
        return word
    return ""


